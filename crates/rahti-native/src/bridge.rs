//! `window.rahtiNative` — the browser side of the capability bridge.
//!
//! ## Why this is a separate script
//!
//! PulsePoint ships as a prebuilt minified bundle, and that bundle is not
//! edited: not by hand, not by a build step, not to add a namespace. So the
//! native surface arrives beside it instead, as the global
//! `window.rahtiNative`, and PulsePoint itself is byte for byte the file a web
//! project serves. The script also attaches the same object as `pp.native`
//! where it can, but a reactive block cannot see that one (its `pp` is a
//! scoped object PulsePoint supplies), so nothing may depend on it.
//!
//! It is framework-owned — generated from this crate rather than written into
//! the application's `public/` — so it cannot drift from [`crate::commands`],
//! and so a project that never opens a native package never serves it.
//!
//! ## The one rule for a page that uses it
//!
//! **The same page has to work as a website.** `window.rahtiNative` is
//! undefined in a browser, and a page that assumed otherwise is a page the
//! project's web deployment breaks on. Every use is guarded. `has` takes a
//! capability name (hyphens), `invoke` a command name (underscores):
//!
//! ```javascript
//! const native = window.rahtiNative;
//! if (native && native.has("choose-file")) {
//!   const file = await native.invoke("choose_file", { extensions: ["png"] });
//! } else {
//!   fileInput.click();   // the web does this perfectly well already
//! }
//! ```
//!
//! ## What it does not do
//!
//! It does not wrap `window.__TAURI__` and re-export it. `invoke` refuses any
//! name that is not in the Rust allowlist before it reaches Tauri, so a page
//! cannot reach a Tauri plugin command that the application never meant to
//! expose merely because the plugin was linked in.

use axum::Router;
use axum::http::{HeaderValue, header};
use axum::response::{IntoResponse, Response};
use axum::routing::get;

/// Where the shell serves the bridge from, for a host that would rather link
/// it than inject it.
pub const BRIDGE_PATH: &str = "/__rahti/native.js";

/// The script, with the current allowlist compiled into it.
///
/// `platform` is the value `window.rahtiNative.platform` reports; the generated shell
/// passes [`crate::Platform::current`].
pub fn bridge_script(platform: &str, version: &str) -> String {
    let commands: Vec<&str> = crate::capabilities::commands()
        .iter()
        .map(|c| c.name)
        .collect();
    script(
        platform,
        version,
        &commands,
        &crate::capabilities::capability_names(),
    )
}

/// The script for a page that is not the package's own: the hosted
/// application an Android package opens when `android.remote` is set.
///
/// That origin is granted no native command, so this bridge offers none:
/// `has` answers `false` for everything and a page takes its web fallback,
/// which is the truth. What is left is what needs no command — links that
/// ask for a new window, and pull to refresh.
pub fn hosted_bridge_script(platform: &str, version: &str) -> String {
    script(platform, version, &[], &[])
}

fn script(platform: &str, version: &str, commands: &[&str], capabilities: &[&str]) -> String {
    let capabilities = json_array(capabilities);
    let allowed = json_array(commands);
    let platform = json_string(platform);
    let version = json_string(version);

    format!(
        r#"// Generated by rahti-native. Do not edit.
//
// Attaches `pp.native` to the PulsePoint runtime. The runtime bundle itself is
// untouched: this listens for the moment it publishes `pp` and adds one
// property to it.
(function () {{
  "use strict";

  var ALLOWED = {allowed};
  var CAPABILITIES = {capabilities};

  function tauri() {{
    var t = window.__TAURI__;
    return t && t.core && typeof t.core.invoke === "function" ? t.core : null;
  }}

  var api = {{
    // `true` inside a native package, and absent everywhere else — which is
    // why a page checks `pp.native` before it checks anything on it.
    available: true,
    platform: {platform},
    version: {version},

    has: function (capability) {{
      return CAPABILITIES.indexOf(capability) !== -1 && tauri() !== null;
    }},

    // Refused here as well as in Rust. This is not the security boundary — the
    // shell's allowlist and Tauri's capability file are — but a name that was
    // never meant to be callable should fail where the caller can see why.
    invoke: function (name, payload) {{
      if (ALLOWED.indexOf(name) === -1) {{
        return Promise.reject(
          new Error("pp.native: `" + name + "` is not a native command this application exposes.")
        );
      }}
      var core = tauri();
      if (!core) {{
        return Promise.reject(new Error("pp.native: the native bridge is not available."));
      }}
      return core.invoke(name, payload || {{}});
    }},
  }};

  Object.freeze(api);

  // The access point a page uses, and the reason it is a global rather than a
  // property of `pp`.
  //
  // PulsePoint compiles the expressions in a reactive block into a function of
  // its own making, and the `pp` visible inside that function is a scoped
  // object it supplies — not `window.pp`. So `pp.state(...)` works there and
  // `pp.native` cannot, without editing the shipped runtime bundle, which is
  // not something Rahti does.
  //
  // `window` *is* reachable from inside a compiled block, so this is.
  window.rahtiNative = api;

  // A target=_blank navigation requests another WebView. Android has no
  // supported new-window hook and desktop WebViews may discard the request,
  // so keep internal links in this window and hand external ones to the
  // deliberately narrow native opener.
  document.addEventListener("click", function (event) {{
    if (event.defaultPrevented || event.button !== 0) return;

    var target = event.target;
    if (target && target.nodeType !== 1) target = target.parentElement;
    var anchor = target && target.closest ? target.closest("a[href]") : null;
    if (!anchor || String(anchor.target).toLowerCase() !== "_blank") return;

    var url;
    try {{
      url = new URL(anchor.href, window.location.href);
    }} catch (_) {{
      return;
    }}

    if (url.origin === window.location.origin) {{
      event.preventDefault();
      window.location.href = url.href;
      return;
    }}
    if (["http:", "https:", "mailto:"].indexOf(url.protocol) === -1) return;

    event.preventDefault();
    api.invoke("open_external", {{ url: url.href }}).catch(function () {{
      // The shell's navigation hook applies the same URL allowlist. This is a
      // safe fallback if Tauri's bridge was unavailable during an early tap.
      window.location.href = url.href;
    }});
  }}, true);

  // Popover is the only hard browser feature used by Rahti UI's overlay
  // components. Do not impose it on applications that render no popover; if
  // one is present, explain an old system WebView instead of leaving controls
  // that silently do nothing.
  function explainOldWebView() {{
    if (typeof HTMLElement !== "undefined" &&
        typeof HTMLElement.prototype.showPopover === "function") return;
    if (!document.body || !document.querySelector("[popover]")) return;
    if (document.getElementById("rahti-webview-compatibility")) return;

    var notice = document.createElement("div");
    notice.id = "rahti-webview-compatibility";
    notice.setAttribute("role", "alert");
    notice.setAttribute("style",
      "position:fixed;z-index:2147483647;inset:0 0 auto 0;padding:12px 16px;" +
      "background:#7f1d1d;color:white;font:14px/1.4 system-ui;text-align:center");
    notice.textContent =
      "This device's WebView is too old for this application's overlays. " +
      "Update Android System WebView or the WebView2 Runtime.";
    document.body.prepend(notice);
  }}

  if (document.readyState === "loading") {{
    document.addEventListener("DOMContentLoaded", explainOldWebView);
  }} else {{
    explainOldWebView();
  }}

  // Pull to refresh, for the pages that ask for it.
  //
  // A WebView has none of its own, and it is not on everywhere because it is
  // not right everywhere: a pull on a half-filled form would throw the form
  // away. A page opts in by putting `data-rahti-pull-to-refresh` on the
  // element that scrolls (or on <html> or <body> when the document does).
  //
  // The pull fires a cancelable `rahti:refresh` event on that element. Left
  // alone, the page reloads. A page that refreshes its own data instead calls
  // `event.preventDefault()` and hands `event.detail.waitUntil` a promise.
  (function () {{
    var TRIGGER = 64;
    var MAX = 96;
    var SIZE = 36;

    var host = null;      // the element that opted in
    var scroller = null;  // what actually scrolls
    var startX = 0;
    var startY = 0;
    var pulling = false;
    var refreshing = false;
    var distance = 0;
    var badge = null;
    var ring = null;
    var spin = 0;

    function draw() {{
      if (!badge) {{
        badge = document.createElement("div");
        badge.setAttribute("aria-hidden", "true");
        var s = badge.style;
        s.position = "fixed";
        s.zIndex = "2147483646";
        s.width = SIZE + "px";
        s.height = SIZE + "px";
        s.marginLeft = -SIZE / 2 + "px";
        s.borderRadius = "50%";
        s.background = "Canvas";
        s.color = "CanvasText";
        s.boxShadow = "0 1px 6px rgba(0,0,0,.3)";
        s.display = "flex";
        s.alignItems = "center";
        s.justifyContent = "center";
        s.pointerEvents = "none";
        ring = document.createElement("div");
        var r = ring.style;
        r.width = "16px";
        r.height = "16px";
        r.borderRadius = "50%";
        r.border = "2.5px solid currentColor";
        r.borderTopColor = "transparent";
        badge.appendChild(ring);
      }}
      if (!badge.isConnected) document.body.appendChild(badge);

      var box = scroller === document.scrollingElement
        ? {{ top: 0, left: 0, width: window.innerWidth }}
        : scroller.getBoundingClientRect();
      var shown = refreshing ? TRIGGER : distance;
      badge.style.left = box.left + box.width / 2 + "px";
      badge.style.top = box.top + "px";
      badge.style.transform = "translateY(" + (shown - SIZE) + "px)";
      badge.style.opacity = String(Math.min(1, shown / TRIGGER));
      ring.style.transform =
        "rotate(" + Math.round(refreshing ? spin : (shown / TRIGGER) * 270) + "deg)";
    }}

    function hide() {{
      pulling = false;
      refreshing = false;
      distance = 0;
      if (badge && badge.isConnected) badge.remove();
    }}

    function turn() {{
      if (!refreshing) return;
      spin = (spin + 9) % 360;
      draw();
      requestAnimationFrame(turn);
    }}

    function refresh() {{
      refreshing = true;
      requestAnimationFrame(turn);

      var pending = null;
      var event = new CustomEvent("rahti:refresh", {{
        bubbles: true,
        cancelable: true,
        detail: {{ waitUntil: function (promise) {{ pending = promise; }} }},
      }});
      if (host.dispatchEvent(event)) {{
        window.location.reload();
        return;
      }}
      Promise.resolve(pending).then(hide, hide);
    }}

    function move(event) {{
      if (refreshing || event.touches.length !== 1) return;
      var dx = event.touches[0].clientX - startX;
      var dy = event.touches[0].clientY - startY;
      if (!pulling) {{
        if (dy <= 10 || Math.abs(dx) > dy || scroller.scrollTop > 0) return;
        pulling = true;
      }}
      // The pull is ours now: the pane must not also overscroll.
      if (event.cancelable) event.preventDefault();
      distance = Math.max(0, Math.min(MAX, (dy - 10) * 0.5));
      draw();
    }}

    function end() {{
      document.removeEventListener("touchmove", move);
      document.removeEventListener("touchend", end);
      document.removeEventListener("touchcancel", end);
      if (refreshing) return;
      if (pulling && distance >= TRIGGER) refresh();
      else hide();
    }}

    document.addEventListener("touchstart", function (event) {{
      if (refreshing || event.touches.length !== 1) return;
      var target = event.target;
      if (target && target.nodeType !== 1) target = target.parentElement;
      host = target && target.closest ? target.closest("[data-rahti-pull-to-refresh]") : null;
      if (!host) return;

      scroller = host === document.documentElement || host === document.body
        ? document.scrollingElement
        : host;
      // Only from the top, and not from inside something of its own that has
      // been scrolled: that drag belongs to the inner list.
      for (var node = target; node && node !== host; node = node.parentElement) {{
        if (node.scrollTop > 0) return;
      }}
      if (!scroller || scroller.scrollTop > 0) return;

      startX = event.touches[0].clientX;
      startY = event.touches[0].clientY;
      pulling = false;
      distance = 0;
      // Not passive, and only while a finger is down on a page that asked.
      document.addEventListener("touchmove", move, {{ passive: false }});
      document.addEventListener("touchend", end);
      document.addEventListener("touchcancel", end);
    }}, {{ passive: true }});
  }})();

  // Best-effort, and documented nowhere as the way in: in a context where
  // `pp` *is* the global object, `pp.native` also works and reads a little
  // better. Nothing depends on it succeeding.
  window.__rahtiNativeAttach = "not attempted";

  function attach(pp) {{
    if (!pp) {{
      return false;
    }}
    if (pp.native) {{
      return true;
    }}
    try {{
      pp.native = api;
    }} catch (e) {{
      window.__rahtiNativeAttach = "assign threw: " + e.message;
    }}
    if (!pp.native) {{
      try {{
        Object.defineProperty(pp, "native", {{
          value: api,
          configurable: true,
          enumerable: true,
        }});
      }} catch (e) {{
        window.__rahtiNativeAttach =
          "frozen=" + Object.isFrozen(pp) + " extensible=" + Object.isExtensible(pp);
        return false;
      }}
    }}
    if (pp.native) {{
      window.__rahtiNativeAttach = "attached";
    }}
    return !!pp.native;
  }}

  // The bundle assigns `globalThis.pp` when it loads, which is after this
  // script runs. Intercepting the assignment is what lets the namespace be
  // added without the bundle knowing anything about it.
  if (!attach(window.pp)) {{
    var stored;
    try {{
      Object.defineProperty(window, "pp", {{
        configurable: true,
        get: function () {{
          return stored;
        }},
        set: function (value) {{
          stored = value;
          attach(value);
        }},
      }});
    }} catch (e) {{
      window.__rahtiNativeAttach = "trap threw: " + e.message;
    }}

    // The trap is not enough on its own, and neither is attaching once.
    //
    // A runtime that publishes itself with `Object.defineProperty` replaces the
    // accessor rather than calling it, so the set never happens. And a runtime
    // that *replaces* `window.pp` later — a richer object after mount, say —
    // silently drops a `native` that was attached to the object before it. Both
    // were observed: the attach reported success and `pp.native` was undefined
    // by the time a page read it.
    //
    // So the attach is not an event, it is a condition that is kept true. The
    // check is a property lookup a few times a second and costs nothing
    // measurable; being wrong costs the whole native surface, silently.
    setInterval(function () {{
      if (window.pp && !window.pp.native) {{
        attach(window.pp);
      }}
    }}, 250);
  }}
}})();
"#
    )
}

/// A route serving the bridge, for a host that links it from the document
/// rather than injecting it at WebView creation.
///
/// Injection is what the generated shell does — it runs before any page script
/// and needs no route — and this exists for the case where that is not
/// available.
pub fn bridge_route(platform: &'static str, version: String) -> Router {
    Router::new().route(
        BRIDGE_PATH,
        get(move || {
            let body = bridge_script(platform, &version);
            async move {
                let mut response = body.into_response();
                response.headers_mut().insert(
                    header::CONTENT_TYPE,
                    HeaderValue::from_static("text/javascript; charset=utf-8"),
                );
                response
                    .headers_mut()
                    .insert(header::CACHE_CONTROL, HeaderValue::from_static("no-store"));
                response as Response
            }
        }),
    )
}

fn json_array(values: &[&str]) -> String {
    let items: Vec<String> = values.iter().map(|v| json_string(v)).collect();
    format!("[{}]", items.join(", "))
}

/// A JSON string literal, with `<` neutralized for the same reason
/// `rahti::Json` does it: this text is written inside a script, and `</script>`
/// in a value would end it.
fn json_string(value: &str) -> String {
    serde_json::to_string(value)
        .unwrap_or_else(|_| "\"\"".to_string())
        .replace('<', "\\u003c")
}
